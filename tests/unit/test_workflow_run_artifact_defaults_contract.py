@pytest.mark.parametrize("case_id", tuple(SOURCES))
def test_versioned_repository_default_and_digest_data_contract(tmp_path: Path, case_id: str) -> None:
    source = SOURCES[case_id]
    workflow = tmp_path / ".github/workflows/ci.yml"
    workflow.parent.mkdir(parents=True)
    workflow.write_text(source, encoding="utf-8", newline="\n")
    result = analyze_corpus(build_corpus(str(tmp_path)))
    verdict = EXPECTED[case_id]
    if verdict == "candidate":
        assert len(result.findings) == 1
        finding = result.findings[0]
        assert finding.review_needed is True
        assert finding.line == next(number for number, line in enumerate(source.splitlines(), 1) if line.strip().removeprefix("- ").startswith("run: bash "))
        assert finding.snippet == source.splitlines()[finding.line - 1].strip()
        assert any("producer identity" in note for note in finding.context_notes)
        assert result.incomplete == ()
    elif verdict == "data":
        assert result.findings == ()
        assert result.incomplete == ()
    else:
        assert verdict == "unknown"
        assert result.findings == ()
        assert result.incomplete
